# Informações
nome = input('Qual é o seu nome: ')
idade = int(input('E a sua idade? '))
cpf = input('Agora digite seu CPF (somente números): ')

# Verificar CPF
if len(cpf) == 11:
    print('CPF com quantidade correta de dígitos')

    # Verificar idade
    if idade >= 12:
        print(f'Olá, {nome}! Cadastro aceito.')
        print('Continue comprando!')
    else:
        print('Não autorizado: idade insuficiente.')

else:
    print('Erro: CPF inválido.')
    print('Cadastro não aceito.')